#!/usr/bin/env node
/*
 * build-13f-example.js — turns the real Berkshire Hathaway 13F in sample-data/form-13f
 * into ownership-dashboard/data/example-13f.js, used by the "Form 13F" learning page
 * to show that one 13F lists many issuers. No network access needed.
 *
 *   node tools/build-13f-example.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const SOI = require('../shared/load-node.js');

const ROOT = path.join(__dirname, '..');
const dir = path.join(ROOT, 'sample-data', 'form-13f');
const files = fs.readdirSync(dir);
const coverName = files.find((f) => f.includes('primary_doc'));
const tableName = files.find((f) => !f.includes('primary_doc') && f.endsWith('.xml'));

(async () => {
  const rec = await new SOI.Parser13F().parse(
    { name: coverName, text: fs.readFileSync(path.join(dir, coverName), 'utf8') },
    { companion: { name: tableName, text: fs.readFileSync(path.join(dir, tableName), 'utf8') } }
  );
  // Filing date from the bundled EDGAR data when available
  let filingDate = rec.filing.filingDate;
  try {
    const bundle = require(path.join(ROOT, 'ownership-dashboard', 'data', 'sec-data.json'));
    const same = bundle.records.find((r) => r.filing.accessionNumber === rec.filing.accessionNumber);
    if (same) filingDate = same.filing.filingDate;
  } catch (e) { /* bundle not generated yet */ }

  // One line per issuer + class + option type (a 13F often splits a position across rows by other manager)
  const by = new Map();
  rec.holdings.forEach((h) => {
    const k = `${h.cusip}|${h.putCall}|${h.sharesType}`;
    const e = by.get(k) || { issuerName: h.issuerName, titleOfClass: h.titleOfClass, cusip: h.cusip, putCall: h.putCall, sharesType: h.sharesType, valueUSD: 0, shares: 0, rows: 0, discretion: new Set(), otherManagers: new Set() };
    e.valueUSD += h.valueUSD || 0;
    e.shares += h.shares || 0;
    e.rows++;
    e.discretion.add(h.investmentDiscretion);
    h.otherManagers.forEach((m) => e.otherManagers.add(m));
    by.set(k, e);
  });
  const issuers = [...by.values()]
    .map((e) => Object.assign(e, { discretion: [...e.discretion], otherManagers: [...e.otherManagers].sort((a, b) => a - b) }))
    .sort((a, b) => b.valueUSD - a.valueUSD);

  const out = {
    filerName: rec.filing.filerName, filerCik: rec.filing.filerCik, formType: rec.filing.formType,
    accessionNumber: rec.filing.accessionNumber, reportPeriod: rec.filing.reportPeriod, filingDate,
    indexUrl: `https://www.sec.gov/Archives/edgar/data/${Number(rec.filing.filerCik)}/${rec.filing.accessionNumber.replace(/-/g, '')}/${rec.filing.accessionNumber}-index.htm`,
    summary: rec.extension.summary, valueUnit: rec.extension.valueUnit,
    otherIncludedManagers: rec.extension.otherIncludedManagers.map((m) => ({ sequenceNumber: m.sequenceNumber, name: m.name })),
    rowsInTable: rec.holdings.length, issuers,
  };
  const file = path.join(ROOT, 'ownership-dashboard', 'data', 'example-13f.js');
  fs.writeFileSync(file, '/* Generated by tools/build-13f-example.js from sample-data/form-13f (real SEC filing). */\nwindow.SOI_EXAMPLE_13F = ' + JSON.stringify(out) + ';\n');
  console.log(`Wrote ${issuers.length} issuer lines from ${rec.holdings.length} rows → ${path.relative(ROOT, file)}`);
})();
