#!/usr/bin/env node
/*
 * build-standalone.js — packs each app into ONE self-contained HTML file:
 *
 *   standalone/ownership-dashboard.html   (includes the SEC data and all libraries)
 *   standalone/sec-filing-parser.html
 *
 * Every <script src> and <link rel="stylesheet"> is inlined, so the files open
 * by double-click, work offline, and can be copied or emailed on their own.
 * The links between the two apps point to each other inside standalone/.
 *
 *   node tools/build-standalone.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'standalone');
fs.mkdirSync(OUT, { recursive: true });

// Inline code must not close its own <script>/<style> element early
const safeScript = (js) => js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
const safeStyle = (css) => css.replace(/<\/style/gi, '<\\/style');

function build(srcHtml, outName, linkMap) {
  const dir = path.dirname(srcHtml);
  let html = fs.readFileSync(srcHtml, 'utf8');
  let bytesIn = 0;
  html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => {
    const css = fs.readFileSync(path.join(dir, href), 'utf8');
    bytesIn += css.length;
    return `<style>/* ${href} */\n${safeStyle(css)}\n</style>`;
  });
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
    const js = fs.readFileSync(path.join(dir, src), 'utf8');
    bytesIn += js.length;
    return `<script>/* ${src} */\n${safeScript(js)}\n</script>`;
  });
  for (const [from, to] of Object.entries(linkMap)) html = html.split(from).join(to);
  html = html.replace('<head>', '<head>\n<!-- Standalone build generated by tools/build-standalone.js. Edit the source files, not this file. -->');
  fs.writeFileSync(path.join(OUT, outName), html);
  const left = (html.match(/<script src=|<link rel="stylesheet" href=/g) || []).length;
  console.log(`${outName}: ${(html.length / 1048576).toFixed(1)} MB${left ? `, WARNING ${left} external reference(s) left` : ''}`);
}

build(path.join(ROOT, 'ownership-dashboard', 'ownership-dashboard.html'), 'ownership-dashboard.html', {
  '../sec-filing-parser/sec-filing-parser.html': 'sec-filing-parser.html',
});
build(path.join(ROOT, 'sec-filing-parser', 'sec-filing-parser.html'), 'sec-filing-parser.html', {
  '../ownership-dashboard/ownership-dashboard.html': 'ownership-dashboard.html',
});
